#!/usr/bin/env node
/**
 * Extracts the platform-agnostic engine chunk out of the single-file demo
 * (IRON-VERGE-playable-demo.html) so it can be exercised headlessly in Node.
 *
 * The demo bundle is one IIFE: engine first, then the browser shell (DemoUI /
 * WebInputController / bootstrap). The shell needs a DOM; the engine does not.
 * This script slices the engine portion, re-exports its symbols, and writes a
 * loadable module to `build/engine.generated.mjs`.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(resolve(root, 'IRON-VERGE-playable-demo.html'), 'utf8');

const IIFE = '(() => {';
const iifeStart = html.indexOf(IIFE);
if (iifeStart < 0) throw new Error('engine IIFE not found');

// The shell begins at the first browser-only module (`// src/web/ui.ts`).
const shellMarkers = ['  // src/web/ui.ts', '  var DemoUI = class {'];
let shellStart = -1;
for (const marker of shellMarkers) {
  const at = html.indexOf(marker, iifeStart);
  if (at >= 0 && (shellStart < 0 || at < shellStart)) shellStart = at;
}
if (shellStart < 0) throw new Error('browser shell boundary not found');

const engine = html.slice(iifeStart + IIFE.length, shellStart);

// Symbols the tests / harness need. Anything not listed is still present in the
// module scope, just not exported.
const EXPORTS = [
  'CONFIG', 'PALETTE', 'INK', 'WEAPON_SPECS', 'ENEMY_STATS', 'WEAPONS', 'CATEGORIES',
  'DEFAULT_MODIFIERS', 'CATALOG', 'CATALOG_BY_ID', 'SAVE_VERSION', 'AD_PLACEMENTS',
  'GameLoop', 'DrawList', 'RNG', 'ParallaxBackground', 'Canvas2DRenderer',
  'InputAdapter', 'EventBus', 'Camera', 'World', 'ParticleSystem', 'ObjectPool',
  'SpawnDirector', 'MockAdService', 'MockIAPService', 'MockReceiptValidator',
  'LocalCloudSave', 'MockRotationBackend', 'BatchedAnalytics',
  'computeRotation', 'hashPayload', 'resolveConflict', 'newIdempotencyKey',
  'createMockServices', 'configureServices', 'createGameStore', 'selectModifiers',
  'selectIsOwned', 'selectShopEntries', 'toPersisted', 'attachPersistence', 'migrate',
  'emptyInput', 'emptyFrame', 'resetFrame', 'buildRenderFrame', 'createPlayer',
  'predictThrow', 'computeThrowVelocity', 'throwGrenade', 'quantize8',
  'segmentAABB', 'explosionDamage', 'consoleAnalytics', 'webKeyValue', 'memoryKeyValue',
  'kvToStateStorage', 'createWeaponRuntime', 'spawnEnemy', 'integrate', 'prune',
];
const missing = EXPORTS.filter((name) => !new RegExp(`(^|\\s)(var|function|const)\\s+${name}\\b`).test(engine));
if (missing.length) throw new Error(`export symbols not found in engine bundle: ${missing.join(', ')}`);

const out = `// GENERATED by scripts/extract-engine.mjs — do not edit.
// Source: IRON-VERGE-playable-demo.html
export default (() => {
${engine.trimEnd()}
  return { ${EXPORTS.join(', ')} };
})();
`;

mkdirSync(resolve(root, 'build'), { recursive: true });
const target = resolve(root, 'build/engine.generated.mjs');
writeFileSync(target, out);
console.log(`wrote ${target} (${(out.length / 1024).toFixed(1)} KB engine-only slice)`);
